-- ENEM 2027 Timão — schema H2 2.x
-- Carga idempotente: CREATE IF NOT EXISTS. Dados iniciais em seed/*.json.

CREATE TABLE IF NOT EXISTS usuario (
    id                   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                 VARCHAR(120) NOT NULL,
    meta_diaria_minutos  INT NOT NULL DEFAULT 90,
    meta_questoes_dia    INT NOT NULL DEFAULT 20,
    criado_em            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS configuracao (
    chave  VARCHAR(60) PRIMARY KEY,
    valor  VARCHAR(400) NOT NULL
);

CREATE TABLE IF NOT EXISTS materia (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(40) NOT NULL UNIQUE,
    nome        VARCHAR(80) NOT NULL,
    area        VARCHAR(40) NOT NULL,
    cor         VARCHAR(9)  NOT NULL,
    prioridade  INT         NOT NULL,
    descricao   VARCHAR(500),
    ordem       INT         NOT NULL
);

CREATE TABLE IF NOT EXISTS topico (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materia_id   INT NOT NULL,
    slug         VARCHAR(90) NOT NULL UNIQUE,
    titulo       VARCHAR(180) NOT NULL,
    resumo       VARCHAR(700),
    dificuldade  VARCHAR(20) NOT NULL,
    fase         INT NOT NULL DEFAULT 1,
    ordem        INT NOT NULL,
    CONSTRAINT fk_topico_materia FOREIGN KEY (materia_id) REFERENCES materia(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS aula (
    id             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topico_id      INT NOT NULL,
    titulo         VARCHAR(180) NOT NULL,
    tipo           VARCHAR(20) NOT NULL DEFAULT 'leitura',
    conteudo       CLOB,
    video_url      VARCHAR(400),
    video_arquivo  VARCHAR(220),
    duracao_min    INT,
    ordem          INT NOT NULL,
    CONSTRAINT fk_aula_topico FOREIGN KEY (topico_id) REFERENCES topico(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS questao (
    id           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(40) NOT NULL UNIQUE,
    topico_id    INT NOT NULL,
    banca        VARCHAR(40) NOT NULL,
    ano          INT,
    fonte        VARCHAR(220),
    autoral      BOOLEAN NOT NULL DEFAULT TRUE,
    dificuldade  VARCHAR(20) NOT NULL,
    enunciado    CLOB NOT NULL,
    gabarito     CHAR(1) NOT NULL,
    comentario   CLOB,
    CONSTRAINT fk_questao_topico FOREIGN KEY (topico_id) REFERENCES topico(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS alternativa (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    questao_id  INT NOT NULL,
    letra       CHAR(1) NOT NULL,
    texto       CLOB NOT NULL,
    CONSTRAINT fk_alt_questao FOREIGN KEY (questao_id) REFERENCES questao(id) ON DELETE CASCADE,
    CONSTRAINT uq_alt_letra UNIQUE (questao_id, letra)
);

CREATE TABLE IF NOT EXISTS flashcard (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     VARCHAR(40) NOT NULL UNIQUE,
    topico_id  INT NOT NULL,
    frente     VARCHAR(600) NOT NULL,
    verso      VARCHAR(1200) NOT NULL,
    dica       VARCHAR(400),
    CONSTRAINT fk_flash_topico FOREIGN KEY (topico_id) REFERENCES topico(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS flashcard_revisao (
    id               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       INT NOT NULL,
    flashcard_id     INT NOT NULL,
    facilidade       DOUBLE NOT NULL DEFAULT 2.5,
    intervalo_dias   INT NOT NULL DEFAULT 0,
    proxima_revisao  DATE,
    acertos          INT NOT NULL DEFAULT 0,
    erros            INT NOT NULL DEFAULT 0,
    ultima_resposta  VARCHAR(20),
    ultima_revisao   TIMESTAMP,
    CONSTRAINT fk_rev_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,
    CONSTRAINT fk_rev_flash FOREIGN KEY (flashcard_id) REFERENCES flashcard(id) ON DELETE CASCADE,
    CONSTRAINT uq_rev_par UNIQUE (usuario_id, flashcard_id)
);

CREATE TABLE IF NOT EXISTS aula_concluida (
    usuario_id    INT NOT NULL,
    aula_id       INT NOT NULL,
    concluido_em  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (usuario_id, aula_id),
    CONSTRAINT fk_ac_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,
    CONSTRAINT fk_ac_aula FOREIGN KEY (aula_id) REFERENCES aula(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS topico_progresso (
    usuario_id       INT NOT NULL,
    topico_id        INT NOT NULL,
    ultima_estudo    DATE,
    aulas_concluidas INT NOT NULL DEFAULT 0,
    revisoes         INT NOT NULL DEFAULT 0,
    proxima_revisao  DATE,
    PRIMARY KEY (usuario_id, topico_id),
    CONSTRAINT fk_tp_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,
    CONSTRAINT fk_tp_topico FOREIGN KEY (topico_id) REFERENCES topico(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS tentativa_questao (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  INT NOT NULL,
    questao_id  INT NOT NULL,
    resposta    CHAR(1) NOT NULL,
    correta     BOOLEAN NOT NULL,
    tempo_seg   INT,
    criado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tq_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,
    CONSTRAINT fk_tq_questao FOREIGN KEY (questao_id) REFERENCES questao(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS sessao_estudo (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  INT NOT NULL,
    data        DATE NOT NULL,
    minutos     INT NOT NULL,
    tipo        VARCHAR(30) NOT NULL,
    descricao   VARCHAR(240),
    CONSTRAINT fk_se_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS redacao (
    id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id      INT NOT NULL,
    titulo          VARCHAR(180) NOT NULL,
    tema            VARCHAR(240),
    texto           CLOB,
    status          VARCHAR(20) NOT NULL DEFAULT 'rascunho',
    nota_estimada   INT,
    criado_em       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_red_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS repertorio (
    id         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     VARCHAR(40) NOT NULL UNIQUE,
    area       VARCHAR(60) NOT NULL,
    titulo     VARCHAR(180) NOT NULL,
    autor      VARCHAR(120),
    citacao    CLOB NOT NULL,
    aplicacao  CLOB,
    tags       VARCHAR(240)
);

CREATE TABLE IF NOT EXISTS tema_redacao (
    id                  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(40) NOT NULL UNIQUE,
    titulo              VARCHAR(240) NOT NULL,
    ano                 INT,
    proposta            CLOB,
    textos_motivadores  CLOB
);

CREATE TABLE IF NOT EXISTS competencia_redacao (
    id          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero      INT NOT NULL UNIQUE,
    titulo      VARCHAR(180) NOT NULL,
    descricao   CLOB,
    criterios   CLOB
);

CREATE INDEX IF NOT EXISTS idx_topico_materia ON topico(materia_id);
CREATE INDEX IF NOT EXISTS idx_aula_topico ON aula(topico_id);
CREATE INDEX IF NOT EXISTS idx_questao_topico ON questao(topico_id);
CREATE INDEX IF NOT EXISTS idx_questao_dificuldade ON questao(dificuldade);
CREATE INDEX IF NOT EXISTS idx_flash_topico ON flashcard(topico_id);
CREATE INDEX IF NOT EXISTS idx_tentativa_questao ON tentativa_questao(questao_id);
CREATE INDEX IF NOT EXISTS idx_sessao_data ON sessao_estudo(data);
